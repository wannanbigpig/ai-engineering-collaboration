from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from zipfile import ZipFile


SCRIPT = Path(__file__).resolve().parents[1] / "scripts/package_skills.py"


class PackageSkillsTest(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name) / "source"
        self.skill = self.root / "skills/example"
        (self.skill / "references").mkdir(parents=True)
        (self.skill / "scripts").mkdir()
        (self.root / "VERSION").write_text("1.2.3\n")
        (self.root / "LICENSE").write_text("Repository license.\n")
        (self.skill / "SKILL.md").write_text(
            "---\nname: example\ndescription: Example.\nmetadata:\n  version: 1.2.3\n---\n"
            "[Reference](references/example.md)\n[Tool](scripts/tool.py)\n"
        )
        (self.skill / "references/example.md").write_text("A complete standalone reference.\n")
        (self.skill / "scripts/tool.py").write_text("#!/usr/bin/env python3\nprint('example')\n")
        (self.skill / "scripts/tool.py").chmod(0o755)

    def run_package(self, destination):
        return subprocess.run(
            [sys.executable, "-B", str(SCRIPT), "--root", str(self.root), "--output", str(destination)],
            capture_output=True, text=True,
        )

    def test_packages_are_deterministic_complete_and_preserve_executable_mode(self):
        first = self.root.parent / "first"
        result = self.run_package(first)
        self.assertEqual(result.returncode, 0, result.stderr)
        for path in self.root.rglob("*"):
            os.utime(path, (1800000000, 1800000000))
        cache = self.skill / "scripts/__pycache__"
        cache.mkdir()
        (cache / "tool.pyc").write_bytes(b"generated bytecode")
        (self.skill / ".DS_Store").write_bytes(b"finder metadata")
        second = self.root.parent / "second"
        second.mkdir()
        result = self.run_package(second)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            {path.name: path.read_bytes() for path in first.iterdir()},
            {path.name: path.read_bytes() for path in second.iterdir()},
        )
        manifest = json.loads((first / "manifest.json").read_text())
        self.assertEqual(manifest["schema_version"], 1)
        self.assertEqual(manifest["version"], "1.2.3")
        package = manifest["skills"][0]
        archive = first / package["archive"]
        self.assertEqual(package["sha256"], hashlib.sha256(archive.read_bytes()).hexdigest())
        expected = {"SKILL.md", "references/example.md", "scripts/tool.py", "LICENSE"}
        self.assertEqual(set(package["files"]), expected)
        with ZipFile(archive) as zipped:
            self.assertEqual(zipped.namelist(), sorted(expected))
            self.assertEqual(zipped.getinfo("scripts/tool.py").external_attr >> 16 & 0o777, 0o755)
            self.assertTrue(all(item.date_time == (1980, 1, 1, 0, 0, 0) for item in zipped.infolist()))
            extracted = self.root.parent / "unpacked"
            zipped.extractall(extracted)
        for name in expected:
            original = self.root / "LICENSE" if name == "LICENSE" else self.skill / name
            self.assertEqual((extracted / name).read_bytes(), original.read_bytes())
            self.assertEqual(package["files"][name]["sha256"], hashlib.sha256(original.read_bytes()).hexdigest())

    def test_real_resource_changes_change_archive_and_file_digests(self):
        before = self.root.parent / "before"
        after = self.root.parent / "after"
        self.assertEqual(self.run_package(before).returncode, 0)
        (self.skill / "references/example.md").write_text("Updated behavior guidance.\n")
        self.assertEqual(self.run_package(after).returncode, 0)
        first = json.loads((before / "manifest.json").read_text())["skills"][0]
        second = json.loads((after / "manifest.json").read_text())["skills"][0]
        self.assertNotEqual(first["sha256"], second["sha256"])
        self.assertNotEqual(first["files"]["references/example.md"], second["files"]["references/example.md"])
        self.assertEqual(first["files"]["SKILL.md"], second["files"]["SKILL.md"])

    def test_skill_license_is_preserved_alongside_repository_license(self):
        (self.skill / "LICENSE").write_text("Skill-specific license.\n")
        destination = self.root.parent / "release"
        result = self.run_package(destination)
        self.assertEqual(result.returncode, 0, result.stderr)
        with ZipFile(destination / "example-1.2.3.zip") as zipped:
            self.assertEqual(zipped.read("LICENSE"), b"Skill-specific license.\n")
            self.assertEqual(zipped.read("LICENSE.repository"), b"Repository license.\n")

    def test_nonempty_destination_and_license_collision_are_not_overwritten(self):
        destination = self.root.parent / "release"
        destination.mkdir()
        sentinel = destination / "keep.txt"
        sentinel.write_text("Existing artifact.\n")
        result = self.run_package(destination)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(sentinel.read_text(), "Existing artifact.\n")
        self.assertEqual(list(destination.iterdir()), [sentinel])
        (self.skill / "LICENSE").write_text("Own license.\n")
        (self.skill / "LICENSE.repository").write_text("Unrelated custom resource.\n")
        other = self.root.parent / "other"
        result = self.run_package(other)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("LICENSE.repository", result.stderr)
        self.assertFalse(other.exists())

    def test_invalid_standalone_package_fails_before_creating_output(self):
        (self.skill / "references/example.md").unlink()
        destination = self.root.parent / "release"
        result = self.run_package(destination)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("missing resource", result.stderr)
        self.assertFalse(destination.exists())

    def test_shipped_query_consumers_run_alone_from_release_archives(self):
        repository = SCRIPT.resolve().parents[1]
        release = self.root.parent / 'actual-release'
        result = subprocess.run([sys.executable, '-B', str(SCRIPT), '--output', str(release)],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        version = (repository / 'VERSION').read_text().strip()
        for name in ('ai-engineering-collaboration', 'code-review', 'systematic-debugging', 'change-impact-analysis'):
            with self.subTest(skill=name):
                isolated = self.root.parent / name
                with ZipFile(release / f'{name}-{version}.zip') as zipped:
                    zipped.extractall(isolated / 'skill')
                project = isolated / 'project'
                records = project / '.aitasks'
                records.mkdir(parents=True)
                (records / 'lessons.md').write_text(
                    '# Lessons\n\n## Legacy invoice\nKeep invoice formatting.\n\n'
                    '<!-- aitasks:lesson id=old status=retired -->\n## Old invoice\nINACTIVE_SENTINEL\n\n'
                    '<!-- aitasks:lesson id=current status=active -->\n## Current invoice\nInvoice format.\n\n'
                    '```markdown\n<!-- aitasks:lesson id=fake status=retired -->\n## Example\n```\n'
                    'CURRENT_END\n\n<!-- aitasks:lesson id=next status=active -->\n## Other\nNEXT_SENTINEL\n')
                snapshot = lambda: {str(p.relative_to(isolated)): p.read_bytes()
                                    for p in isolated.rglob('*') if p.is_file()}
                before = snapshot()
                command = [sys.executable, '-B', str(isolated / 'skill/scripts/query_aitasks.py'),
                           '--project-root', str(project)]
                context = subprocess.run(command + ['context', '--query', 'invoice'], capture_output=True, text=True)
                self.assertEqual(context.returncode, 0, context.stderr)
                summaries = json.loads(context.stdout)['lessons']
                self.assertEqual(len(summaries), 2)
                self.assertIn('current', {row['id'] for row in summaries})
                self.assertNotIn('INACTIVE_SENTINEL', context.stdout)
                detail = subprocess.run(command + ['get-record', '--kind', 'lesson', '--id', 'current'],
                                        capture_output=True, text=True)
                self.assertEqual(detail.returncode, 0, detail.stderr)
                content = json.loads(detail.stdout)['content']
                self.assertIn('CURRENT_END', content)
                self.assertNotIn('NEXT_SENTINEL', content)
                self.assertEqual(snapshot(), before)
                self.assertFalse((isolated / 'skill/scripts/maintain_aitasks.py').exists())
    def test_source_links_and_output_inside_skill_are_rejected(self):
        destination = self.root.parent / "release"
        external = self.root.parent / "outside.txt"
        external.write_text("Outside source package.\n")
        link = self.skill / "external.txt"
        link.symlink_to(external)
        result = self.run_package(destination)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Symlinked skill content", result.stderr)
        self.assertFalse(destination.exists())
        link.unlink()
        nested_output = self.skill / "release"
        result = self.run_package(nested_output)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("outside the source skills", result.stderr)
        self.assertFalse(nested_output.exists())


if __name__ == "__main__":
    unittest.main()
